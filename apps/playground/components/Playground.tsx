"use client";

import { useCallback, useState } from "react";
import { useEndpointHealth, type FriendlyError } from "@/lib/client";
import type { SnippetInput } from "@/lib/snippets";
import ChatPanel from "./ChatPanel";
import CodePanel from "./CodePanel";
import StatusPill, { StatusNotice } from "./StatusPill";
import TranslatePanel from "./TranslatePanel";

type Tab = "chat" | "translate";

export default function Playground() {
  const [tab, setTab] = useState<Tab>("chat");
  const [snippet, setSnippet] = useState<SnippetInput | null>(null);
  const { status, latencyMs, refresh } = useEndpointHealth();

  const onSnippet = useCallback((s: SnippetInput) => setSnippet(s), []);
  const onEndpointProblem = useCallback(
    (kind: FriendlyError["kind"]) => {
      if (kind === "offline" || kind === "loading" || kind === "config") void refresh();
    },
    [refresh],
  );

  return (
    <div className="flex min-h-screen flex-col">
      <div className="flag-stripe h-1.5 w-full" aria-hidden />
      <header className="border-b border-slate-200/70 bg-white/80 backdrop-blur">
        <div className="mx-auto flex max-w-7xl flex-wrap items-center justify-between gap-3 px-5 py-4">
          <div className="flex items-center gap-3">
            <div className="grid h-10 w-10 place-items-center rounded-xl bg-naija-600 text-lg font-black text-white shadow-sm">N</div>
            <div>
              <h1 className="text-lg font-bold leading-tight tracking-tight text-slate-900">N-ATLaS Playground</h1>
              <p className="text-xs text-slate-500">Yorùbá · Hausa · Igbo · Nigerian English · built on natlas-js</p>
            </div>
          </div>
          <div className="flex items-center gap-2">
            <StatusPill status={status} latencyMs={latencyMs} onRefresh={refresh} />
            <a
              href="https://github.com/olaxbonnke/natlas-js"
              target="_blank"
              rel="noreferrer"
              className="btn-ghost border border-slate-200 bg-white"
            >
              GitHub
            </a>
          </div>
        </div>
      </header>

      <main className="mx-auto w-full max-w-7xl flex-1 px-5 py-6">
        <StatusNotice status={status} />

        <div className="mb-4 inline-flex rounded-xl border border-slate-200 bg-white p-1 shadow-sm" role="tablist">
          {(
            [
              ["chat", "Chat"],
              ["translate", "Translate"],
            ] as const
          ).map(([id, label]) => (
            <button
              key={id}
              role="tab"
              type="button"
              aria-selected={tab === id}
              onClick={() => setTab(id)}
              className={`rounded-lg px-5 py-2 text-sm font-semibold transition ${
                tab === id ? "bg-naija-600 text-white shadow-sm" : "text-slate-600 hover:text-slate-900"
              }`}
            >
              {label}
            </button>
          ))}
        </div>

        <div className="grid items-start gap-6 lg:grid-cols-[minmax(0,1fr)_420px]">
          <div>
            {tab === "chat" ? (
              <ChatPanel onSnippet={onSnippet} onEndpointProblem={onEndpointProblem} />
            ) : (
              <TranslatePanel onSnippet={onSnippet} onEndpointProblem={onEndpointProblem} />
            )}
          </div>
          <CodePanel input={snippet} />
        </div>
      </main>

      <footer className="border-t border-slate-200/70 bg-white">
        <div className="mx-auto max-w-7xl px-5 py-5 text-xs leading-relaxed text-slate-500">
          <p>
            <strong className="text-slate-700">Every response on this page is generated by N-ATLaS</strong>; no other
            foundation model is used. N-ATLaS is an initiative of the Federal Ministry of Communications, Innovation and
            Digital Economy, and powered by Awarri Technologies, with NCAIR/NITDA. Model use is subject to the{" "}
            <a className="underline underline-offset-2" href="https://huggingface.co/NCAIR1/N-ATLaS" target="_blank" rel="noreferrer">
              N-ATLaS Terms of Use
            </a>
            .
          </p>
          <p className="mt-1">
            natlas-js is open source (MIT) by{" "}
            <a className="underline underline-offset-2" href="https://github.com/olaxbonnke" target="_blank" rel="noreferrer">
              Bonnke Olaitan
            </a>{" "}
            for the Nigeria AI Challenge (PS1 · Developer Infrastructure). Outputs can be wrong; check important content with a fluent speaker.
          </p>
        </div>
      </footer>
    </div>
  );
}
